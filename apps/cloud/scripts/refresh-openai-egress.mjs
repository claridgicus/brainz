#!/usr/bin/env node
/**
 * Regenerate src/lib/server/openai-egress.ts from OpenAI's published ChatGPT
 * integrations egress list (plugins, connectors, GPT Actions):
 *   https://openai.com/chatgpt-connectors.json
 * listed on https://developers.openai.com/api/docs/guides/ip-addresses, which
 * says the ranges "can change as OpenAI infrastructure changes" — re-run this
 * periodically (and before a directory submission). A stale snapshot is safe:
 * an unlisted OpenAI address just falls back to the normal per-bucket DCR limit.
 *
 *   node scripts/refresh-openai-egress.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = "https://openai.com/chatgpt-connectors.json";
const out = fileURLToPath(new URL("../src/lib/server/openai-egress.ts", import.meta.url));

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
const doc = await res.json();
const v4 = [];
const v6 = [];
for (const p of doc.prefixes ?? []) {
  if (typeof p.ipv4Prefix === "string") v4.push(p.ipv4Prefix);
  if (typeof p.ipv6Prefix === "string") v6.push(p.ipv6Prefix);
}
if (v4.length + v6.length === 0) throw new Error("no prefixes in the published list; refusing to write an empty snapshot");

const lines = (xs) => xs.map((x) => `  ${JSON.stringify(x)},`).join("\n");
writeFileSync(
  out,
  `/**
 * GENERATED by scripts/refresh-openai-egress.mjs — do not edit by hand.
 *
 * OpenAI's published egress ranges for ChatGPT integrations (plugins,
 * connectors, GPT Actions), from ${SOURCE}
 * (documented at https://developers.openai.com/api/docs/guides/ip-addresses).
 * Snapshot creationTime: ${doc.creationTime}. The ranges change over time;
 * re-run the script to refresh. Used only to exempt ChatGPT's dynamic client
 * registrations from the per-bucket DCR limit (see $lib/server/oauth).
 */
export const OPENAI_EGRESS_CREATION_TIME = ${JSON.stringify(doc.creationTime)};

export const OPENAI_EGRESS_IPV4: readonly string[] = [
${lines(v4)}
];

export const OPENAI_EGRESS_IPV6: readonly string[] = [
${lines(v6)}
];
`,
);
console.log(`wrote ${v4.length} IPv4 + ${v6.length} IPv6 prefixes (creationTime ${doc.creationTime})`);
